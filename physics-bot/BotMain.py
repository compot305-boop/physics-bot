_RU_ENDINGS = [
    "иями", "ями", "ами", "ией", "иях", "ях", "ах", "ов", "ев", "ий", "ый",
    "ой", "ей", "ая", "яя", "ое", "ее", "ые", "ие", "ым", "им", "ыми", "ими",
    "ую", "юю", "ешь", "ишь", "ете", "ите", "ут", "ют", "ат", "ят", "ла", "ло",
    "ли", "ть", "ся", "сь", "ом", "ем", "ам", "ям", "ы", "и", "а", "я", "е",
    "у", "ю", "о", "ь"
]

def _stem_word(word: str) -> str:
    w = word.lower()
    for end in _RU_ENDINGS:
        if len(w) > len(end) + 2 and w.endswith(end):
            return w[: -len(end)]
    return w

def normalize_text(text: str) -> str:
    if not text:
        return ""
    text = text.lower()
    text = re.sub(r"[^a-zа-яё0-9\s]", " ", text)
    words = text.split()
    return " ".join(_stem_word(w) for w in words if w)

def build_search_index():
    index = []
    for grade, topics in FORMULAS.items():
        for topic, data in topics.items():
            norm_topic = normalize_text(topic)
            norm_text = normalize_text(data["text"])
            norm_formula = normalize_text(data["formula"])
            index.append({
                "grade": grade,
                "topic": topic,
                "haystack": f"{norm_topic} {norm_text} {norm_formula}"
            })
    return index

SEARCH_INDEX = build_search_index()

def search_formulas(query: str):
    norm_query = normalize_text(query)
    if not norm_query:
        return []
    query_words = norm_query.split()
    results = []
    for item in SEARCH_INDEX:
        haystack = item["haystack"]
        if all(word in haystack for word in query_words):
            results.append((item["grade"], item["topic"]))
    return results

