def _censor_topic(text: str, topic: str) -> str:
    clean = text.replace("**", "")
    topic_clean = re.sub(r"\(.*?\)", "", topic).strip().lower()
    topic_words = [w for w in re.split(r"\s+", topic_clean) if len(w) > 3]
    stems = [_stem_word(w) for w in topic_words]

    tokens = re.findall(r"[А-Яа-яЁёA-Za-z\-]+|[^\sА-Яа-яЁёA-Za-z]+", clean)
    result = []
    for tok in tokens:
        if re.match(r"[А-Яа-яЁёA-Za-z\-]+", tok):
            tok_stem = _stem_word(tok.lower())
            if tok_stem in stems:
                result.append("…")
                continue
        result.append(tok)
    censored = "".join(result)
    censored = re.sub(r"\s+", " ", censored).strip()
    return censored

def generate_quiz_question(mode: str, used_topics: set, pool: list):
    available = [t for t in pool if (t["grade"], t["topic"]) not in used_topics]
    if not available:
        return None

    correct_item = random.choice(available)

    others_pool = [t for t in ALL_TOPICS
                   if (t["grade"], t["topic"]) != (correct_item["grade"], correct_item["topic"])]
    random.shuffle(others_pool)
    wrong_items = others_pool[:3]

    actual_mode = mode
    if mode in ["time", "marathon"]:
        actual_mode = random.choice(["formula", "definition"])

    if actual_mode == "formula":
        question_text = f"📐 Какая тема соответствует формуле:\n\n**{correct_item['formula']}** ?"
        correct_answer = correct_item["topic"]
    else:
        first_sentence = correct_item["text"].split(".")[0].strip()
        censored = _censor_topic(first_sentence, correct_item["topic"])
        if len(censored) > 200:
            censored = censored[:197] + "..."
        question_text = f"📖 Какая тема соответствует определению:\n\n_{censored}_"
        correct_answer = correct_item["topic"]

    options = [correct_answer] + [w["topic"] for w in wrong_items]
    random.shuffle(options)
    correct_idx = options.index(correct_answer)

    return {
        "mode": mode,
        "actual_mode": actual_mode,
        "question": question_text,
        "options": options,
        "correct": correct_idx,
        "correct_topic": correct_item["topic"],
        "correct_grade": correct_item["grade"],
        "key": (correct_item["grade"], correct_item["topic"]),
    }

